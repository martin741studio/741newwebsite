#!/usr/bin/env python3
"""Place a validated job description where the agent loads it, update the roster, write _run.json.
Run ONLY after Martin's card Go for this file (the chat enforces the card; this script just writes).

usage:
  place.py --id ID --rung rules [--paths "00_project/assets/suriya/**,..."]   # .claude/rules/agents/<id>.md
  place.py --id ID --rung task  --task TASK_ID                                # header block in ~/.claude/scheduled-tasks/<task>/SKILL.md
  place.py --id ID --rung memory                                              # prints the MEMORY.md pointer line only
"""
import argparse, json, re, sys, datetime, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
DATA = ROOT / "00_project" / "agent-jobs"
HOME = Path.home()
START, END = "<!-- agent-job:start -->", "<!-- agent-job:end -->"

def _h(name): return re.compile(r"\*\*" + re.escape(name) + r"(?: \([^)]*\))?:\*\*")
def section(src, name, nxt):
    a = _h(name).search(src); b = _h(nxt).search(src, a.end()) if a else None
    return src[a.start():b.start()] if a and b else ""

def main():
    p = argparse.ArgumentParser(); p.add_argument("--id", required=True); p.add_argument("--rung", required=True, choices=["rules", "task", "memory"])
    p.add_argument("--paths"); p.add_argument("--task")
    a = p.parse_args()
    src_path = DATA / f"{a.id}.md"
    if not src_path.exists(): sys.exit(f"no description at {src_path}")
    v = subprocess.run([sys.executable, str(Path(__file__).with_name("validate_jd.py")), str(src_path)], capture_output=True, text=True)
    if v.returncode != 0: sys.exit("validator FAIL — not placing:\n" + v.stdout)
    src = src_path.read_text()
    roster = json.loads((DATA / "roster.json").read_text())
    ag = next((x for x in roster["agents"] if x["id"] == a.id), None) or sys.exit(f"{a.id} not in roster")
    placed = []
    if a.rung == "rules":
        paths = [x for x in (a.paths or ",".join(ag.get("paths", []))).split(",") if x]
        if not paths: sys.exit("rules rung needs --paths or roster paths (otherwise the rule loads in every session)")
        out = ROOT / ".claude" / "rules" / "agents" / f"{a.id}.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        fm = "---\npaths:\n" + "".join(f"  - \"{x}\"\n" for x in paths) + "---\n"
        out.write_text(fm + f"<!-- generated by agent-job-descriptions/place.py from {ag['description']} — do not edit here -->\n\n" + src)
        placed.append(str(out.relative_to(ROOT))); ag["paths"] = paths
    elif a.rung == "task":
        task = a.task or ag.get("task") or sys.exit("task rung needs --task")
        f = HOME / ".claude" / "scheduled-tasks" / task / "SKILL.md"
        if not f.exists(): sys.exit(f"no scheduled task at {f}")
        block = "\n".join([START, f"Job description (source of truth: {ag['description']}; edit there, re-run place.py):",
                           section(src, "Actions that need a Go", "Never (rung)").strip(),
                           section(src, "Never (rung)", "Caps").strip(), section(src, "Caps", "May delegate to").strip(), END])
        t = f.read_text()
        if START in t: t = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda m: block, t, flags=re.S)
        else:
            parts = t.split("---", 2)
            t = ("---" + parts[1] + "---\n" + block + "\n" + parts[2]) if t.startswith("---") and len(parts) == 3 else block + "\n" + t
        f.write_text(t); placed.append(str(f)); ag["task"] = task
    else:
        print(f"- [{ag['title']} job description]({ag['description']}) — agent `{a.id}`, {ag['type']}, review Friday; never-lines and Go lists inside")
        return
    for x in placed:
        if x not in ag.setdefault("placed_at", []): ag["placed_at"].append(x)
    ag["status"] = "active"
    (DATA / "roster.json").write_text(json.dumps(roster, indent=1, ensure_ascii=False) + "\n")
    day = datetime.date.today().isoformat()
    run = ROOT / "00_project" / "assets" / "741studio" / "agent-job-descriptions" / day
    run.mkdir(parents=True, exist_ok=True)
    (run / "_run.json").write_text(json.dumps({"client": "741 Studio (intern)", "workflow": "agent-job-descriptions", "status": "fertig",
        "mode": "Echt", "last_run": day, "result": ag["description"], "note": f"placed {a.id} at {', '.join(placed)}"}, indent=1, ensure_ascii=False) + "\n")
    print("placed:", *placed, sep="\n  "); print(f"_run.json: {run / '_run.json'}")

if __name__ == "__main__":
    main()
