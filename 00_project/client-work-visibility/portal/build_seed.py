  "select v.cid::uuid, (select id from work_phases p where p.client_id = v.cid::uuid and p.status = 'current' limit 1), 'task', v.title, v.st, v.w, v.reason, v.prio,\n"
  f"  {A('Martin')}, (select id from work_actors a where a.name = v.doer and a.client_id is null limit 1), v.due::date, v.nxt, 'grill', v.sid\n"
